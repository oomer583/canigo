// Interface language. The English sentence is the key, so a missing translation still shows English.
// To add a language: add it to UI_LANGS and add a block to DICT with the same keys.
// Default: the browser's language if we have it, otherwise English. The user's choice is remembered.

export const UI_LANGS = [
  { id: 'en', label: 'English' },
  { id: 'tr', label: 'Türkçe' },
  { id: 'az', label: 'Azərbaycanca' },
  { id: 'ru', label: 'Русский' }
]

const KEY = 'canigo.lang'
let current = 'en'

export function detectLang(saved, browser = []) {
  const ids = UI_LANGS.map((l) => l.id)
  if (ids.includes(saved)) return saved
  for (const b of browser) {
    const base = String(b).toLowerCase().split('-')[0]
    if (ids.includes(base)) return base
  }
  return 'en'
}

export function loadLang() {
  let saved = null
  try {
    saved = localStorage.getItem(KEY)
  } catch {
    // storage unavailable
  }
  const browser = typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : []
  return detectLang(saved, browser)
}

export function saveLang(id) {
  try {
    localStorage.setItem(KEY, id)
  } catch {
    // works for this visit
  }
}

export function setLanguage(id) {
  current = DICT[id] ? id : 'en'
}

export function t(key, vars) {
  const text = DICT[current]?.[key] || DICT.en[key] || key
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m)) : text
}

